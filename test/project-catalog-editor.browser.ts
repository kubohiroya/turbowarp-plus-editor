import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import path from 'node:path';
import test from 'node:test';
import {chromium, expect} from '@playwright/test';
import JSZip from '@turbowarp/jszip';
import {verifyWebEditor} from '../scripts/site/editor-revision.ts';

test('the real Editor records successful SB3 opens and saves both kinds of rename through its native services',
    {timeout: 90000}, async t => {
        const root = process.env.E2E_PROJECT_FOLDER_BUILD;
        assert.ok(root && path.isAbsolute(root), 'Set E2E_PROJECT_FOLDER_BUILD to the local Editor build');
        await verifyWebEditor(root);
        const browser = await chromium.launch({headless: true, args: ['--enable-unsafe-swiftshader']});
        t.after(() => browser.close());
        const page = await browser.newPage({viewport: {width: 1360, height: 900}});
        const errors: string[] = [];
        page.on('pageerror', error => errors.push(error.message));
        const origin = 'http://localhost:41225';
        const prefix = '/turbowarp-plus-editor/';
        await page.route('**/*', async route => {
            const url = new URL(route.request().url());
            if (url.origin !== origin || !url.pathname.startsWith(prefix)) return route.abort();
            const filename = path.resolve(root, decodeURIComponent(url.pathname.slice(prefix.length)));
            if (!filename.startsWith(root + path.sep)) return route.abort();
            const body = await readFile(filename).catch(() => null);
            if (!body) return route.fulfill({status: 404});
            const mime = {'.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json',
                '.svg': 'image/svg+xml', '.png': 'image/png', '.wasm': 'application/wasm'};
            await route.fulfill({body, contentType: mime[path.extname(filename)] || 'application/octet-stream'});
        });
        await page.addInitScript(() => {
            const w = window as any;
            w.showOpenFilePicker = location.search.includes('catalogPicker=input') ? undefined : async () => {
                if (w.cancelPicker) {w.cancelled = true; throw new DOMException('Cancelled', 'AbortError');}
                return [w.catalogFile];
            };
        });
        const ready = () => page.waitForFunction(() => (window as any).vm?.runtime.getTargetForStage() &&
            (window as any).ScratchBlocks?.getMainWorkspace(), null, {timeout: 45000});
        await page.goto(`${origin}${prefix}editor.html?lang=en`);
        await ready();
        const defaultTitle = await page.evaluate(() => (window as any).ReduxStore.getState().scratchGui.projectTitle);
        const bytes = await page.evaluate(async () => Array.from(await (window as any).vm.saveProjectSb3('uint8array') as Uint8Array));
        const zip = await JSZip.loadAsync(new Uint8Array(bytes));
        const project = JSON.parse(await zip.file('project.json')!.async('string'));
        project.turboWarpPlusProject = {schemaVersion: 1, title: 'Catalog fixture'};
        zip.file('project.json', JSON.stringify(project));
        const fixture = [...await zip.generateAsync({type: 'uint8array'})];
        await page.evaluate(async bytes => {
            const directory = await navigator.storage.getDirectory();
            const file = await directory.getFileHandle('catalog-fixture.sb3', {create: true});
            const writer = await file.createWritable(); await writer.write(new Uint8Array(bytes)); await writer.close();
            (window as any).catalogFile = file;
        }, fixture);
        const menu = async (command: string) => {
            await page.getByText('File', {exact: true}).first().click();
            await page.getByText(command, {exact: true}).click();
        };
        await menu('Open SB3 File…');
        await page.waitForFunction(() => (window as any).ReduxStore.getState().scratchGui.projectTitle === 'Catalog fixture');
        await menu('Projects…');
        await expect(page.locator('[data-project-id] strong')).toHaveText(['Catalog fixture']);
        const id = await page.locator('[data-project-id]').getAttribute('data-project-id');
        await page.locator('[data-catalog-action=close]').click();
        await page.evaluate(() => {(window as any).cancelPicker = true;});
        await menu('Open SB3 File…');
        await page.waitForFunction(() => (window as any).cancelled === true);
        await menu('Projects…');
        await expect(page.locator('[data-project-id]')).toHaveCount(1);
        assert.equal(await page.locator('[data-project-id]').getAttribute('data-project-id'), id);
        await page.locator('[data-catalog-action=rename-title]').click();
        await page.locator('input[name=title]').fill('Catalog renamed');
        await page.locator('form button[type=submit]').click();
        await expect(page.locator('[data-project-id] strong')).toHaveText(['Catalog renamed']);
        const savedBytes = await page.evaluate(async () => [...new Uint8Array(await (await (window as any).catalogFile.getFile()).arrayBuffer())]);
        const saved = await JSZip.loadAsync(new Uint8Array(savedBytes));
        assert.equal(JSON.parse(await saved.file('project.json')!.async('string')).turboWarpPlusProject.title, 'Catalog renamed');
        await page.locator('[data-catalog-action=rename-storage]').click();
        await page.locator('input[name=storageName]').fill('renamed-storage');
        await page.locator('form button[type=submit]').click();
        await expect(page.locator('[data-project-id]')).toContainText('renamed-storage.sb3');
        await page.locator('[data-catalog-action=close]').click();
        await page.reload(); await ready();
        await menu('Projects…');
        await expect(page.locator('[data-project-id] strong')).toHaveText(['Catalog renamed']);
        assert.equal(await page.locator('[data-project-id]').getAttribute('data-project-id'), id);
        await page.locator('[data-catalog-action=open]').click();
        await expect(page.locator('[data-project-catalog]')).toHaveCount(0);
        await page.waitForFunction(() => (window as any).ReduxStore.getState().scratchGui.projectTitle === 'Catalog renamed');
        await menu('Projects…');
        await expect(page.locator('[data-project-id]')).toHaveCount(1);
        await page.locator('[data-catalog-action=forget]').click();
        await expect(page.locator('[data-project-id]')).toHaveCount(0);
        assert.equal(await page.evaluate(async () => (await (await navigator.storage.getDirectory()).getFileHandle('renamed-storage.sb3')).kind), 'file');
        await page.locator('[data-catalog-action=close]').click();
        await page.goto(`${origin}${prefix}editor.html?lang=en&catalogPicker=input`); await ready();
        const choose = page.waitForEvent('filechooser');
        await menu('Open SB3 File…');
        await (await choose).setFiles({name: 'input-fallback.sb3', mimeType: 'application/octet-stream', buffer: Buffer.from(fixture)});
        await page.waitForFunction(() => (window as any).ReduxStore.getState().scratchGui.projectTitle === 'Catalog fixture');
        await menu('Projects…');
        await expect(page.locator('[data-project-id]')).toHaveCount(1);
        await expect(page.locator('[data-project-id]')).toContainText('input-fallback.sb3');
        await expect(page.locator('[data-catalog-action=rename-title]')).toBeDisabled();
        const fallbackId = await page.locator('[data-project-id]').getAttribute('data-project-id');
        const reselect = page.waitForEvent('filechooser');
        await page.locator('[data-catalog-action=open]').click();
        await (await reselect).setFiles({name: 'input-fallback.sb3', mimeType: 'application/octet-stream', buffer: Buffer.from(fixture)});
        await expect(page.locator('[data-project-catalog]')).toHaveCount(0);
        await menu('Projects…');
        await expect(page.locator('[data-project-id]')).toHaveCount(1);
        assert.equal(await page.locator('[data-project-id]').getAttribute('data-project-id'), fallbackId);
        if (process.env.CATALOG_CREATE_SCREENSHOT) await page.screenshot({path: process.env.CATALOG_CREATE_SCREENSHOT});
        await page.locator('[data-catalog-action=create]').click();
        await expect(page.locator('[data-project-catalog]')).toHaveCount(0);
        const creation = page.locator('[data-new-project-dialog]');
        await expect(creation).toBeVisible();
        await expect(creation.locator('input[name=destination][value=browser]')).toHaveCount(1);
        assert.equal(await page.evaluate(() => (window as any).ReduxStore.getState().scratchGui.projectTitle), 'Catalog fixture');
        await creation.locator('[data-new-project-cancel]').click();
        await expect(creation).toHaveCount(0);
        assert.equal(await page.evaluate(() => (window as any).ReduxStore.getState().scratchGui.projectTitle), 'Catalog fixture');
        await menu('Projects…');
        await page.locator('[data-catalog-action=create]').click();
        await creation.locator('input[name=destination][value=memory]').check();
        await creation.locator('button[type=submit]').click();
        await expect(creation).toHaveCount(0);
        await page.waitForFunction(title => (window as any).ReduxStore.getState().scratchGui.projectTitle === title, defaultTitle);
        assert.deepEqual(errors, []);
    });
